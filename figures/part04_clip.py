"""Part 4 figure: PPO's clipped surrogate for one token, as a function of the ratio rho = pi_theta / pi_old.

    L(rho) = min(rho * A, clip(rho, 1 - eps, 1 + eps) * A),  eps = 0.2.

Left: A = +1. Right: A = -1. The dashed line is the unclipped surrogate rho * A. Shaded: the ratios where
the clipped objective is flat, so the token gets no gradient. The dot at rho = 1 is where every update
starts when the rollouts were generated by the current policy (pi_theta = pi_old).
checks/part04_checks.py recomputes the values quoted in the post.
Run: python figures/part04_clip.py  ->  assets/part-04/clip.png
"""
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

plt.rcParams.update({"font.size": 10, "axes.titlesize": 10, "axes.labelsize": 10,
                     "xtick.labelsize": 9, "ytick.labelsize": 9, "legend.fontsize": 9,
                     "axes.spines.top": False, "axes.spines.right": False})
CLIPPED = "#08519c"
UNCLIPPED = "#888888"
FLAT = "#e6e6e6"
EPS = 0.2


def clipped(rho: np.ndarray, A: float) -> np.ndarray:
    return np.minimum(rho * A, np.clip(rho, 1 - EPS, 1 + EPS) * A)


def main(out: Path = Path(__file__).resolve().parents[1] / "assets/part-04/clip.png") -> None:
    rho = np.linspace(0.0, 2.0, 801)
    fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.3))
    box = dict(fc="white", ec="none", pad=0.8)
    for ax, A in zip(axes, (1.0, -1.0)):
        lo, hi = (1 + EPS, 2.0) if A > 0 else (0.0, 1 - EPS)
        ax.axvspan(lo, hi, color=FLAT, zorder=0, lw=0)
        ax.plot(rho, rho * A, color=UNCLIPPED, lw=1.3, ls="--", label="unclipped, ρA")
        ax.plot(rho, clipped(rho, A), color=CLIPPED, lw=2.2, label="clipped objective")
        for x in (1 - EPS, 1 + EPS):
            ax.axvline(x, color=UNCLIPPED, lw=0.8, ls=":", zorder=1)
        ax.plot([1.0], [A], "o", ms=5.5, color=CLIPPED, zorder=4)
        ax.set_xlim(0, 2)
        ax.set_xticks([0, 0.5, 0.8, 1.0, 1.2, 1.5, 2.0], ["0", "0.5", "0.8", "1", "1.2", "1.5", "2"])
        ax.set_xlabel("Ratio ρ = π_θ / π_old for the token")
        if A > 0:
            ax.set_ylim(-0.05, 2.05)
            ax.set_ylabel("Objective for the token")
            ax.set_title("A > 0: raising ρ pays only up to 1 + ε", loc="left")
            ax.text(1.6, 0.55, "flat: no gradient", ha="center", va="center", color="#555555", fontsize=9)
            ax.annotate("ρ = 1: π_θ = π_old", (1.0, 1.0), xytext=(-8, 44), textcoords="offset points",
                        ha="right", fontsize=9, color=CLIPPED, bbox=box,
                        arrowprops=dict(arrowstyle="-", color=CLIPPED, lw=0.8, shrinkA=0, shrinkB=4))
            ax.text(0.36, 1.02, "below 1 − ε the\nmin keeps ρA:\nfull gradient", ha="center", va="center",
                    fontsize=9, color="#555555")
            ax.legend(loc="upper left", frameon=False, handlelength=1.8, borderaxespad=0.2)
        else:
            ax.set_ylim(-2.05, 0.05)
            ax.set_title("A < 0: lowering ρ pays only down to 1 − ε", loc="left")
            ax.text(0.4, -1.8, "flat: no gradient", ha="center", va="center", color="#555555", fontsize=9)
            ax.annotate("ρ = 1: π_θ = π_old", (1.0, -1.0), xytext=(-10, -30), textcoords="offset points",
                        ha="right", fontsize=9, color=CLIPPED, bbox=box,
                        arrowprops=dict(arrowstyle="-", color=CLIPPED, lw=0.8, shrinkA=0, shrinkB=4))
            ax.text(1.62, -0.75, "above 1 + ε the\nmin keeps ρA:\nfull gradient", ha="center", va="center",
                    fontsize=9, color="#555555")
    fig.tight_layout(w_pad=2.0)
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=200, bbox_inches="tight")
    for A in (1.0, -1.0):
        print(f"A={A:+.0f}: L(0.7)={clipped(np.array(0.7), A):+.2f}, L(1.3)={clipped(np.array(1.3), A):+.2f}")
    return fig


if __name__ == "__main__":
    main()
